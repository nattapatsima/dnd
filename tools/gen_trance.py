"""Build js/trance-options.js: the PHB'24 weapons and tools a Shadar-Kai Trance can add.

Run from the sheet folder:  python tools/gen_trance.py ../5etools/data
Lists only what the build is not already proficient with (Rogue: simple weapons and martial
weapons with Finesse or Light; Thieves' and Woodcarver's tools). The Hunting Rifle is the
fixed first Trance pick, so it is not in the list.
"""
import json
import re
import sys
from pathlib import Path

DATA = Path(sys.argv[1] if len(sys.argv) > 1 else '../5etools/data')
OUT = Path(__file__).resolve().parent.parent / 'js' / 'trance-options.js'
OWNED_TOOLS = {"Thieves' Tools", "Woodcarver's Tools"}
ABILITY = {'Strength': 'str', 'Dexterity': 'dex', 'Constitution': 'con',
           'Intelligence': 'int', 'Wisdom': 'wis', 'Charisma': 'cha'}
DAMAGE = {'P': 'piercing', 'S': 'slashing', 'B': 'bludgeoning'}


def plain(text):
    return re.sub(r'\{@\w+ ([^|}]*)[^}]*\}', r'\1', text)


def props(item):
    return {(p['uid'] if isinstance(p, dict) else p).split('|')[0] for p in item.get('property') or []}


def kind(item):
    return item['type'].split('|')[0]


def load(name):
    with open(DATA / name, encoding='utf-8') as f:
        return json.load(f)


base = [x for x in load('items-base.json')['baseitem'] if x.get('source') == 'XPHB']
items = [x for x in load('items.json')['item'] if x.get('source') == 'XPHB']

weapons = []
for w in base:
    if w.get('weaponCategory') != 'martial' or props(w) & {'F', 'L'}:
        continue
    ranged = kind(w) == 'R'
    die = w['dmg1'] if 'd' in str(w['dmg1']) else str(w['dmg1'])
    entry = {
        'id': re.sub(r'\W+', '-', w['name'].lower()).strip('-'),
        'name': w['name'],
        'kind': 'ranged' if ranged else 'melee',
        'ability': 'dex' if ranged else 'str',
        'die': die,
        'damageType': DAMAGE[w['dmgType']],
    }
    if w.get('range'):
        entry['range'] = [int(n) for n in w['range'].split('/')]
    weapons.append(entry)

tools = []
for t in base + items:
    if kind(t) not in ('AT', 'T', 'GS', 'INS') or t['name'] in OWNED_TOOLS:
        continue
    fields = {}
    for block in t.get('entries', []):
        for row in (block.get('items', []) if isinstance(block, dict) else []):
            if isinstance(row, dict) and row.get('name') in ('Ability:', 'Utilize:'):
                fields[row['name']] = plain(' '.join(row.get('entries', [])))
    ability = ABILITY.get(fields.get('Ability:', '').split()[0] if fields.get('Ability:') else '', None)
    use = fields.get('Utilize:', '')
    # "Identify a substance (15), or start a fire (15)" -> "identify a substance (DC 15), or start a fire (DC 15)"
    use = re.sub(r'\s*\((\d+)\)', r' (DC \1)', use).strip().rstrip(',.')
    if not ability:
        ability = 'cha' if kind(t) == 'INS' else 'wis'
    tools.append({
        'id': re.sub(r'\W+', '-', t['name'].lower()).strip('-'),
        'name': t['name'],
        'ability': ability,
        'use': use[:1].lower() + use[1:] if use else 'ability check',
    })

weapons.sort(key=lambda w: w['name'])
tools.sort(key=lambda t: t['name'])
header = ('// Generated by tools/gen_trance.py from the 5e.tools PHB\'24 data. Do not edit by hand.\n'
          '// Weapons and tools the Trance second pick can add (ones the build lacks).\n')
OUT.write_text(header
               + 'export const TRANCE_WEAPONS = ' + json.dumps(weapons, indent=2, ensure_ascii=False) + ';\n\n'
               + 'export const TRANCE_TOOLS = ' + json.dumps(tools, indent=2, ensure_ascii=False) + ';\n',
               encoding='utf-8', newline='\n')
print(f'{len(weapons)} weapons, {len(tools)} tools -> {OUT}')
